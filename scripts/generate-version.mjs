#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const target = new URL('../nodes/version.ts', import.meta.url);
const content = `// Generated by npm run generate.\nexport const packageVersion = '${version}';\n`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* Missing is stale. */
  }
  if (current !== content) {
    console.error('nodes/version.ts is stale — run npm run generate');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, content);
}
